export function isValidGalleryReviewId(value: string): boolean {
  return GALLERY_REVIEW_ID_PATTERN.test(value);
}

export function galleryReviewPath(reviewId: string): string {
  return `/gallery/${encodeURIComponent(reviewId)}`;
}

export function normalizeGalleryImageType(value: string | null | undefined): ConversionImageType {
  return KNOWN_IMAGE_TYPES.includes(value as ConversionImageType) ? (value as ConversionImageType) : 'default';
}

function collapseWhitespace(value: string): string {
  return value.replace(/\s+/g, ' ').trim();
}

function truncate(value: string, maxLength: number): string {
  const normalized = collapseWhitespace(value);
  if (normalized.length <= maxLength) return normalized;
  return `${normalized.slice(0, Math.max(0, maxLength - 1)).trimEnd()}…`;
}

/** The language the critique itself is written in, which drives the indexable article copy. */
export function resolveGalleryReviewContentLocale(
  review: Pick<PublicGalleryReview, 'review_locale' | 'advantage' | 'critique' | 'suggestions'>,
): SupportedLocale {
  const declared = (review.review_locale ?? '').trim().toLowerCase();
  if (declared === 'zh' || declared === 'en' || declared === 'ja') return declared;
  const text = `${review.advantage}${review.critique}${review.suggestions}`;
  if (/[぀-ヿ]/.test(text)) return 'ja';
  if (/[一-鿿]/.test(text)) return 'zh';
  return 'en';
}

export function getGalleryReviewArticleCopy(locale: string | null | undefined): ArticleCopy {
  return ARTICLE_COPY[normalizeLocale(locale)];
}

export function getGalleryReviewChromeCopy(locale: string | null | undefined): ChromeCopy {
  return CHROME_COPY[normalizeLocale(locale)];
}

export function getGalleryImageTypeLabel(locale: string | null | undefined, imageType: string): string {
  return ARTICLE_COPY[normalizeLocale(locale)].imageTypes[normalizeGalleryImageType(imageType)];
}

export function formatGalleryScore(score: number): string {
  return Number.isFinite(score) ? score.toFixed(1) : '0.0';
}

export function buildGalleryReviewHeading(review: Pick<PublicGalleryReview, 'image_type' | 'final_score' | 'review_locale' | 'advantage' | 'critique' | 'suggestions'>): string {
  const locale = resolveGalleryReviewContentLocale(review);
  const copy = ARTICLE_COPY[locale];
  return copy.heading(copy.imageTypes[normalizeGalleryImageType(review.image_type)], formatGalleryScore(review.final_score));
}

/** Topic-only metadata title (the root template appends the brand); unique per critique via a summary snippet. */
export function buildGalleryReviewTitle(review: PublicGalleryReview): string {
  const locale = resolveGalleryReviewContentLocale(review);
  const heading = buildGalleryReviewHeading(review);
  const snippet = truncate(review.summary || review.advantage || review.critique, locale === 'en' ? 34 : 18);
  return snippet ? `${heading}${ARTICLE_COPY[locale].titleSnippetSeparator}${snippet}` : heading;
}

export function buildGalleryReviewDescription(review: PublicGalleryReview): string {
  const source = [review.advantage, review.critique, review.suggestions].filter(Boolean).join(' ');
  return truncate(source || review.summary, 160);
}

export function isIndexableGalleryReview(review: Pick<PublicGalleryReview, 'advantage' | 'critique' | 'suggestions'>): boolean {
  const text = collapseWhitespace(`${review.advantage} ${review.critique} ${review.suggestions}`);
  return text.length >= GALLERY_REVIEW_MIN_INDEXABLE_TEXT;
}

export function buildGalleryReviewWorkspaceHref(review: Pick<PublicGalleryReview, 'review_id' | 'image_type'>): string {
  return buildWorkspaceConversionHref({
    source: 'gallery',
    entrypoint: 'gallery_detail',
    imageType: normalizeGalleryImageType(review.image_type),
    galleryReviewId: review.review_id,
  });
}

export function buildGalleryTypeFilterHref(imageType: string): string {
  const normalized = normalizeGalleryImageType(imageType);
  return normalized === 'default' ? '/gallery' : `/gallery?image_type=${normalized}`;
}

type StructuredDataSite = {
  url: string;
  name: string;
  websiteId?: string;
  organizationId?: string;
};

/**
 * ImageObject + WebPage markup. No Review/Rating rich-result markup: an AI score
 * of a user's own photo is not an independent review and must not be presented
 * as one.
 */
export function buildGalleryReviewJsonLd({ site, review }: { site: StructuredDataSite; review: PublicGalleryReview }) {
  const pageUrl = `${site.url}${galleryReviewPath(review.review_id)}`;
  const locale = resolveGalleryReviewContentLocale(review);
  const title = buildGalleryReviewHeading(review);
  const description = buildGalleryReviewDescription(review);
  const author = review.owner_profile_url
    ? { '@type': 'Person', name: review.owner_username, url: `${site.url}${review.owner_profile_url}` }
    : undefined;

  return {
    '@context': 'https://schema.org',
    '@type': 'WebPage',
    '@id': `${pageUrl}#webpage`,
    url: pageUrl,
    name: title,
    description,
    inLanguage: locale,
    datePublished: review.gallery_added_at,
    dateModified: review.updated_at,
    isPartOf: { '@id': site.websiteId ?? `${site.url}/#website` },
    publisher: { '@id': site.organizationId ?? `${site.url}/#organization` },
    ...(review.photo_thumbnail_url
      ? {
          primaryImageOfPage: {
            '@type': 'ImageObject',
            contentUrl: review.photo_thumbnail_url,
            caption: title,
            ...(author ? { creator: author } : {}),
          },
        }
      : {}),
  };
}

function escapeXml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

export function buildGallerySitemapXml(siteUrl: string, entries: readonly GallerySitemapEntry[]): string {
  const urls = entries
    .filter((entry) => isValidGalleryReviewId(entry.review_id))
    .map((entry) => {
      const lastModified = new Date(entry.last_modified);
      const lastmod = Number.isNaN(lastModified.getTime()) ? '' : `<lastmod>${lastModified.toISOString()}</lastmod>`;
      return `<url><loc>${escapeXml(`${siteUrl}${galleryReviewPath(entry.review_id)}`)}</loc>${lastmod}<changefreq>monthly</changefreq><priority>0.6</priority></url>`;
    });
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${urls.join('')}</urlset>\n`;
}

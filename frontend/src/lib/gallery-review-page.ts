/**
 * Public, indexable Gallery critique pages (`/gallery/[reviewId]`).
 *
 * Only Gallery-approved critiques reach these pages; share-link-only critiques
 * stay on the noindex `/share/*` surface. The backend projection deliberately
 * omits EXIF, notes, practice data, score feedback and paired comparisons.
 */

